-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- -------------------------------------------------------------------------
-- 1. USERS TABLE
-- Stores customers and administrator accounts.
-- (Retains intentional client-side auth & lab educational vulnerabilities)
-- -------------------------------------------------------------------------
create table if not exists public.users (
    id bigint generated by default as identity primary key,
    name text not null,
    email text unique not null,
    password text not null,
    role text default 'customer' not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security (RLS) with open public access for demo / pentesting
alter table public.users enable row level security;

create policy "Allow public read access on users" 
    on public.users for select 
    using (true);

create policy "Allow public insert on users" 
    on public.users for insert 
    with check (true);

create policy "Allow public update on users" 
    on public.users for update 
    using (true);

create policy "Allow public delete on users" 
    on public.users for delete 
    using (true);

-- -------------------------------------------------------------------------
-- 2. PRODUCTS TABLE
-- Botanical inventory catalog.
-- -------------------------------------------------------------------------
create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    price numeric(10, 2) not null,
    original_price numeric(10, 2),
    rating numeric(3, 1) default 4.8,
    review_count integer default 15,
    colors text[],
    image text not null,
    description text not null,
    stock integer default 50 not null,
    featured boolean default true,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.products enable row level security;

create policy "Allow public read on products" 
    on public.products for select 
    using (true);

create policy "Allow public insert on products" 
    on public.products for insert 
    with check (true);

create policy "Allow public update on products" 
    on public.products for update 
    using (true);

create policy "Allow public delete on products" 
    on public.products for delete 
    using (true);

-- -------------------------------------------------------------------------
-- 3. ORDERS TABLE
-- Customer purchases and transactions.
-- (Vulnerability 5: Insecure Direct Object Reference (IDOR) via ?id=...)
-- -------------------------------------------------------------------------
create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    customer_name text not null,
    email text not null,
    phone text not null,
    address text not null,
    items jsonb not null default '[]'::jsonb,
    total numeric(10, 2) not null,
    status text default 'Processing' not null,
    order_date date default current_date not null,
    delivery_date date,
    notes text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.orders enable row level security;

create policy "Allow public read on orders" 
    on public.orders for select 
    using (true);

create policy "Allow public insert on orders" 
    on public.orders for insert 
    with check (true);

create policy "Allow public update on orders" 
    on public.orders for update 
    using (true);

-- -------------------------------------------------------------------------
-- 4. REVIEWS TABLE
-- Product feedback.
-- (Vulnerability 2: Stored XSS sink via unescaped comment rendering)
-- -------------------------------------------------------------------------
create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    product_id bigint references public.products(id) on delete cascade,
    author text not null,
    rating integer default 5 not null,
    comment text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.reviews enable row level security;

create policy "Allow public read on reviews" 
    on public.reviews for select 
    using (true);

create policy "Allow public insert on reviews" 
    on public.reviews for insert 
    with check (true);

